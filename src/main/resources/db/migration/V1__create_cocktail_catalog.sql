CREATE TABLE cocktail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    summary VARCHAR(280) NOT NULL,
    spirit VARCHAR(40) NOT NULL,
    glass VARCHAR(60) NOT NULL,
    instructions VARCHAR(800) NOT NULL,
    alcoholic BOOLEAN NOT NULL,
    min_temperature_c DOUBLE PRECISION NOT NULL,
    max_temperature_c DOUBLE PRECISION NOT NULL,
    flavor_tags VARCHAR(220) NOT NULL,
    color_start VARCHAR(20) NOT NULL,
    color_end VARCHAR(20) NOT NULL,
    CONSTRAINT ck_cocktail_temperature CHECK (min_temperature_c <= max_temperature_c)
);

CREATE TABLE ingredient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cocktail_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    amount VARCHAR(60) NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_ingredient_cocktail
        FOREIGN KEY (cocktail_id) REFERENCES cocktail(id) ON DELETE CASCADE,
    CONSTRAINT uq_ingredient_order UNIQUE (cocktail_id, display_order)
);

CREATE INDEX idx_cocktail_preferences
    ON cocktail (spirit, alcoholic, min_temperature_c, max_temperature_c);
CREATE INDEX idx_ingredient_cocktail ON ingredient (cocktail_id);

